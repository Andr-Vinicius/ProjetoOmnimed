CREATE TABLE MEDICOS (
    MED_ID INT NOT NULL,
    FK_FUNCIONARIOS_FUN_ID INT NOT NULL,
    FK_FUNCIONARIOS_FK_USUARIO_COMUM_USC_ID INT NOT NULL,
    PRIMARY KEY (MED_ID, FK_FUNCIONARIOS_FUN_ID, FK_FUNCIONARIOS_FK_USUARIO_COMUM_USC_ID)
);

CREATE TABLE FUNCIONARIOS (
    FUN_ID INT AUTO_INCREMENT,
    FK_USUARIO_COMUM_USC_ID INT NOT NULL,
    PRIMARY KEY (FUN_ID, FK_USUARIO_COMUM_USC_ID)
);

CREATE TABLE DEPENDENTES (
