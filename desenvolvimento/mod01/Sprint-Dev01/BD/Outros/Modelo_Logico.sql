    FK_PACIENTES_PAC_ID INT NOT NULL,
    FK_PACIENTES_FK_USUARIO_COMUM_USC_ID INT NOT NULL,
    PRIMARY KEY (FK_PACIENTES_PAC_ID, FK_PACIENTES_FK_USUARIO_COMUM_USC_ID)
);

CREATE TABLE CONTABILIDADE (
