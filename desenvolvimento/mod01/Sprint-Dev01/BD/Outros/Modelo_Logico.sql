CREATE TABLE ENFERMEIROS (
    ENF_ID INT AUTO_INCREMENT,
    FK_FUNCIONARIOS_FUN_ID INT NOT NULL,
    FK_FUNCIONARIOS_FK_USUARIO_COMUM_USC_ID INT NOT NULL,
    PRIMARY KEY (ENF_ID, FK_FUNCIONARIOS_FUN_ID, FK_FUNCIONARIOS_FK_USUARIO_COMUM_USC_ID)
